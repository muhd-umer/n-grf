function Users = createUsers(env_dims, val, array, distribution)
    if distribution == "uniform"
        [X, Y] = meshgrid(...
            env_dims(1,1):val:env_dims(1,2), ...
            env_dims(2,1):val:env_dims(2,2));
        positions = [X(:)'; Y(:)'; unifrnd(0.5, 1.5, [1, numel(X)])];
    else
        numUsers = val;
        positions = [...
            unifrnd(env_dims(1,1), env_dims(1,2), [1, numUsers]); ...
            unifrnd(env_dims(2,1), env_dims(2,2), [1, numUsers]); ...
            unifrnd(0.25, 1.25, [1, numUsers]) ...
        ];
    end
    
    Users = rxsite("cartesian", ...
        "Antenna", array, ...
        "AntennaPosition", positions);
end